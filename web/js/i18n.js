export function tr(key, vars = {}) {
  const lang = getState("lang");
  const table = I18N[lang] || I18N.id;
  const fallback = I18N.id[key] || key;
  const template = table[key] || fallback;
  return String(template).replace(/\{(\w+)\}/g, (_, name) =>
    vars[name] === undefined || vars[name] === null ? "" : String(vars[name])
  );
}

export function trHtml(key, vars = {}) {
  // Same as tr but caller will assign with .innerHTML.
  return tr(key, vars);
}

export function initLang() {
  const stored = localStorage.getItem(LANG_KEY);
  const initial = stored && SUPPORTED.has(stored) ? stored : "id";
  setState("lang", initial);
  document.documentElement.lang = initial;
}

export function setLanguage(lang) {
  if (!SUPPORTED.has(lang)) return;
  setState("lang", lang);
  localStorage.setItem(LANG_KEY, lang);
  document.documentElement.lang = lang;
}

export function onLangChange(fn) {
  return subscribe("lang", fn);
}

export function currentLang() {
  return getState("lang");
}
